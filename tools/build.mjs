import {readFile,writeFile,copyFile} from 'node:fs/promises';
const root=new URL('../',import.meta.url);
const model=(await readFile(new URL('model.mjs',root),'utf8')).replace(/^export /gm,'');
const app=await readFile(new URL('app.source.js',root),'utf8');
await writeFile(new URL('dist/app.js',root),`/* Generated by npm run build. Edit model.mjs and app.source.js. */\n(()=>{\n'use strict';\n${model}\n${app}\n})();\n`);
for(const file of ['index.html','style.css']) await copyFile(new URL(`src/${file}`,root),new URL(`dist/${file}`,root));
console.log('Готово: dist/ — интерфейс Лиги.');
